#!/usr/bin/env python3
"""Convert a Spleen BDF font into a C glyph table for the custom UI.

Glyphs: ASCII 0x20..0x7E, then the extra Latin-1 characters in EXTRA (German
umlauts etc.), in that order. UI strings are Latin-1; glyph_index() in lcd.c
maps a byte to its slot. Each glyph is H rows of ceil(W/8) bytes, MSB = left.

Usage: fontgen.py <font.bdf> <c_name>   (writes C to stdout)
"""
import sys

EXTRA = 'äöüÄÖÜß°'          # keep in sync with glyph_index() in lcd.c

def load(path):
    glyphs, w, h, cur, rows = {}, None, None, None, None
    for line in open(path, encoding='latin-1'):
        p = line.split()
        if not p:
            continue
        if p[0] == 'FONTBOUNDINGBOX':
            w, h = int(p[1]), int(p[2])
        elif p[0] == 'ENCODING':
            cur = int(p[1])
        elif p[0] == 'BITMAP':
            rows = []
        elif p[0] == 'ENDCHAR':
            glyphs[cur], rows = rows, None
        elif rows is not None:
            rows.append(p[0])
    return w, h, glyphs

def main(path, name):
    w, h, glyphs = load(path)
    bpr = (w + 7) // 8
    codes = list(range(0x20, 0x7F)) + [ord(c) for c in EXTRA]
    out = ['/* Generated by ui/fontgen.py from %s (Spleen, BSD-2, see fonts/LICENSE.spleen). */'
           % path.split('/')[-1],
           'const unsigned char %s[%d] = {' % (name, len(codes) * h * bpr)]
    for c in codes:
        rows = glyphs[c]
        assert len(rows) == h, (c, len(rows))
        data = []
        for r in rows:
            v = int(r, 16)
            data += [(v >> (8 * (len(r) // 2 - 1 - i))) & 0xff for i in range(bpr)]
        out.append('  ' + ','.join('0x%02x' % b for b in data) + ',  /* %r */' % chr(c))
    out.append('};')
    print('\n'.join(out))

if __name__ == '__main__':
    main(*sys.argv[1:])
